#!/usr/bin/env python3
"""
gen_preloader_stub.py - build the import stub the mod links against.

WHY THIS EXISTS
---------------
LeviLaunchroid loads a mod with System.load() -> dlopen(RTLD_NOW). Mod .so files
are built with BIND_NOW, so EVERY undefined symbol must resolve at load time.
The launcher loads libpreloader.so only *after* System.load(), so a mod that
references pl::* symbols without declaring libpreloader.so as a DT_NEEDED
dependency dies with:

    dlopen failed: cannot locate symbol "_ZN2pl3mod9NativeMod7currentEv"

Declaring the dependency makes the linker load libpreloader.so (it ships in the
APK at lib/<abi>/libpreloader.so) and resolve the symbols. To emit that
DT_NEEDED entry we must link against something named libpreloader.so, so we
generate a stub with the same soname. The stub is a link-time artifact only -
it is NEVER shipped in the .levipack; the real library satisfies the symbols at
runtime.

Usage:
    gen_preloader_stub.py <built-mod.so> <output-dir> [--ndk <ndk-root>]
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

# pl:: symbols plus the C entry points the launcher exports.
FUNC_PREFIXES = ("_ZN2pl", "_ZNK2pl", "_ZN2PL", "PL")
DATA_PREFIXES = ("_ZTI", "_ZTS", "_ZTV")
SYMBOL_RE = re.compile(r"^\s*U\s+(\S+)\s*$", re.MULTILINE)


def find_ndk(explicit: str | None) -> Path:
    candidates = [
        explicit,
        os.environ.get("ANDROID_NDK_HOME"),
        "/home/user/.cache/ndk/android-ndk-r28c",
    ]
    for c in candidates:
        if c and (Path(c) / "toolchains" / "llvm").is_dir():
            return Path(c)
    raise SystemExit("!! Android NDK not found (set ANDROID_NDK_HOME)")


def undefined_symbols(nm: Path, so: Path) -> list[str]:
    out = subprocess.run([str(nm), "-D", "--undefined-only", str(so)],
                         capture_output=True, text=True, check=True).stdout
    return [m.group(1) for m in SYMBOL_RE.finditer(out)]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("library")
    ap.add_argument("outdir")
    ap.add_argument("--ndk")
    args = ap.parse_args()

    ndk = find_ndk(args.ndk)
    bindir = ndk / "toolchains" / "llvm" / "prebuilt" / "linux-x86_64" / "bin"
    nm = bindir / "llvm-nm"
    clang = bindir / "clang"

    so = Path(args.library)
    outdir = Path(args.outdir)
    outdir.mkdir(parents=True, exist_ok=True)

    symbols = undefined_symbols(nm, so)
    funcs = [s for s in symbols if s.startswith(FUNC_PREFIXES) and not s.startswith(DATA_PREFIXES)]
    datas = [s for s in symbols if s.startswith(DATA_PREFIXES)]

    if not funcs and not datas:
        print("[stub] no preloader symbols needed - nothing to do")
        return 0

    asm = [
        "// generated by gen_preloader_stub.py - link-time stub only",
        ".text",
    ]
    for s in funcs:
        asm += [
            ".p2align 2",
            f".globl {s}",
            f".type {s}, %function",
            f"{s}:",
            "  ret",
            f".size {s}, .-{s}",
        ]
    if datas:
        asm.append(".section .bss")
        for s in datas:
            asm += [
                ".p2align 3",
                f".globl {s}",
                f".type {s}, %object",
                f"{s}:",
                "  .zero 64",
                f".size {s}, 64",
            ]

    src = outdir / "preloader_stub.S"
    lib = outdir / "libpreloader.so"
    src.write_text("\n".join(asm) + "\n")

    subprocess.run([
        str(clang), "--target=aarch64-linux-android28",
        "-shared", "-nostdlib", "-fPIC",
        "-Wl,-soname,libpreloader.so",
        "-o", str(lib), str(src),
    ], check=True)

    print(f"[stub] libpreloader.so: {len(funcs)} functions, {len(datas)} objects")
    for s in funcs:
        print(f"       {s}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
